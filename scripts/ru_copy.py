_NBSP = "\u00a0"
_PREP = re.compile(
    r"(?<![\w-])("
    r"[Вв]о|[Дд]о|[Дд]ля|[Зз]а|[Ии]з|[Кк]о|[Нн]ад|[Оо]б|[Оо]т|[Пп]од|[Пп]ри|[Пп]ро|[Сс]о|"
    r"[Вв]|[Кк]|[Сс]|[Оо]|[Уу]|[Ии]|[Аа]|[Нн]о|[Дд]а|[Нн]е|[Нн]и|[Нн]а|[Пп]о"
    r")[ \t]+"
)


def _typograph_chunk(text: str) -> str:
    text = re.sub(r"[ \t\u00a0]*—[ \t\u00a0]*", _NBSP + "— ", text)
    text = re.sub(r"(\d)[ \t]+(?=[А-Яа-яЁё])", r"\1" + _NBSP, text)
    text = _PREP.sub(lambda m: m.group(1) + _NBSP, text)
    text = re.sub(r"\u00a0—[ \t]*", _NBSP + "— ", text)
    text = re.sub(r"[ \t]+\u00a0", _NBSP, text)
    return text


def typograph(text: str) -> str:
    """Ёлочки и буква ё задаются в тексте. Здесь — тире и неразрывные пробелы."""
    if not text:
        return text
    out: list[str] = []
    i = 0
    while i < len(text):
        nxt = len(text)
        found = None
        for phrase in _FROZEN:
            j = text.find(phrase, i)
            if j != -1 and j < nxt:
                nxt = j
                found = phrase
        if found is None:
            out.append(_typograph_chunk(text[i:]))
            break
        out.append(_typograph_chunk(text[i:nxt]))
        out.append(found)
        i = nxt + len(found)
    return "".join(out)


